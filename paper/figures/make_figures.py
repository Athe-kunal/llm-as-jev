"""Builds paper/generated/: the figures (PDF), the headline table and numbers.tex (\\newcommand per number).

  .venv/bin/python paper/figures/make_figures.py
"""
import json
import pathlib
import sys

import matplotlib.pyplot as plt

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import data   # noqa: E402
import make_examples  # noqa: E402
import style  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "generated"
# Macro-safe names (LaTeX command names cannot contain digits or underscores).
MACRO = {"ub_sig": "UbSig", "ub_list": "UbList", "qw_full": "QwFull", "qw_lora": "QwLora", "qw4_lora": "QwFourLora"}


def pct(x):
    return f"{100 * x:.1f}"


def fig_headline(h):
    """Test ALL with 95% intervals, one row per model, best at the top."""
    keys = sorted((k for k in h if h[k]["test"]), key=lambda k: h[k]["test"][0])
    fig, ax = plt.subplots(figsize=(style.COLUMN, 0.32 * len(keys) + 0.55))
    for y, k in enumerate(keys):
        m, (pt, lo, hi) = data.MODELS[k], h[k]["test"]
        c = style.FAMILY[m["family"]]
        ax.plot(100 * pt, y, "o", ms=6.5, color=c if m["ours"] else "white", mec=c, mew=1.5, zorder=3)
        ax.text(100 * pt + 1.0, y, pct(pt), va="center", fontsize=7.5, color=style.INK)
    ax.set_yticks(range(len(keys)), [data.MODELS[k]["short"] for k in keys])
    ax.set_xlabel("Test accuracy, ALL (%)")
    ax.grid(axis="y", visible=False)
    lo = min(100 * h[k]["test"][0] for k in keys)
    hi = max(100 * h[k]["test"][0] for k in keys)
    ax.set_xlim(lo - 3, hi + 4)
    ax.set_ylim(-0.6, len(keys) - 0.4)
    handles = [plt.Line2D([], [], marker="o", ls="-", color=style.ENCODER, ms=5, label="Encoder"),
               plt.Line2D([], [], marker="o", ls="-", color=style.DECODER, ms=5, mfc="white", label="Decoder")]
    ax.legend(handles=handles, loc="lower right", handlelength=1.4)
    fig.savefig(OUT / "fig_headline.pdf")
    plt.close(fig)


def fig_paired(diffs):
    """Paired test differences (first − second) with 95% intervals; zero = no difference."""
    items = list(diffs.items())[::-1]
    fig, ax = plt.subplots(figsize=(style.COLUMN, 0.32 * len(items) + 0.55))
    ax.axvline(0, color=style.INK_2, lw=0.8, ls=(0, (3, 2)))
    for y, ((a, b), (pt, lo, hi)) in enumerate(items):
        c = style.FAMILY[data.MODELS[a]["family"]]
        ax.plot([100 * lo, 100 * hi], [y, y], color=c, lw=1.5)
        ax.plot(100 * pt, y, "o", ms=5.5, color=c, zorder=3)
        ax.text(100 * hi + 0.25, y, f"{100 * pt:+.1f}", va="center", fontsize=7.5, color=style.INK)
    ax.set_yticks(range(len(items)), [f"{data.MODELS[a]['short']}\n− {data.MODELS[b]['short']}" for (a, b), _ in items],
                  fontsize=6.8)
    ax.set_xlabel("Paired difference on test rows (points)")
    ax.grid(axis="y", visible=False)
    ax.set_xlim(min(-0.5, min(100 * v[1] for _, v in items) - 0.5), max(100 * v[2] for _, v in items) + 1.5)
    ax.set_ylim(-0.6, len(items) - 0.4)
    fig.savefig(OUT / "fig_paired.pdf")
    plt.close(fig)


def table_headline(h):
    """booktabs table: params, dev ALL, test ALL, external macro (means); best test below 1B in bold."""
    def cell(ms):
        return "--" if ms[0] is None else pct(ms[0])
    best_test = max(h[k]["test"][0] for k in h if h[k]["test"] and data.MODELS[k]["params"] != "4B")
    rows = []
    for k in ("ub_sig", "ub_list", "qw_full", "qw_lora", "qw4_lora"):
        m, r = data.MODELS[k], h[k]
        pt = r["test"][0]
        test = f"\\textbf{{{pct(pt)}}}" if pt == best_test else pct(pt)
        if k == "qw4_lora":
            rows.append("\\midrule")
        rows.append(f"{m['name']} & {m['params']} & {cell(r['dev'])} & {test} & {cell(r['ext'])} \\\\")
    body = "\n".join(rows)
    (OUT / "table_headline.tex").write_text(
        "% Generated by paper/figures/make_figures.py; do not edit.\n"
        "\\begin{tabular}{@{}llccc@{}}\n\\toprule\n"
        "Model & Params & Dev ALL & Test ALL & External \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def table_perdataset(h):
    """Test accuracy per dataset (seed-averaged), best below 1B in bold; the number of rows per dataset."""
    pd_ = data.per_dataset(h)
    cols = ("ub_sig", "ub_list", "qw_full", "qw_lora", "qw4_lora")
    small = cols[:4]
    rows = []
    for i, (key, name) in enumerate(data.DATASETS):
        if i in (3, 9):
            rows.append("\\midrule")
        vals = {k: pd_[k][key][0] for k in cols}
        best = max(vals[k] for k in small)
        cells = [f"\\textbf{{{pct(vals[k])}}}" if vals[k] == best and k in small else pct(vals[k]) for k in cols]
        rows.append(f"{name} & {pd_['ub_sig'][key][1]} & " + " & ".join(cells) + " \\\\")
    head = "Dataset & Rows & UB sig-norm & UB softmax & Qwen full & Qwen LoRA & Qwen-4B LoRA"
    (OUT / "table_perdataset.tex").write_text(
        "% Generated by paper/figures/make_figures.py; do not edit.\n"
        "\\begin{tabular}{@{}lrccccc@{}}\n\\toprule\n" + head + " \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


ABLATION = [("Softmax, ``yes''", "ultrabert_380m_lr1.5e-5"),
            ("Softmax, ``yes'' $-$ ``no''", "ultrabert_380m_lr1.5e-5_yesno"),
            ("Sigmoid-norm, ``yes'' $-$ ``no''", "ultrabert_380m_lr1.5e-5_sigmoidnorm"),
            ("Softmax, ``correct''", "ultrabert_380m_lr1.5e-5_correctB"),
            ("Softmax, ``correct'' $-$ ``incorrect''", "ultrabert_380m_lr1.5e-5_correctC")]


EV_LIST = "evidence_ultrabert_380m"            # head on the softmax-trained encoder (AT2 and ContextCite explain this one)
EV_SIG = "evidence_ultrabert_380m_sigmoidnorm"  # head on the sigmoid-normalised encoder


def table_citation():
    """Citation methods on the 200 evidence rows: sentence AP, top-1 gold, faithfulness (LDS), time per row."""
    att = json.loads((data.RUNS / "at2_ultrabert_380m" / "attribution_eval.json").read_text())["summary"]["ALL"]
    rows = [(name, att[key]["ap"], att[key]["top1"], f"{att[key]['lds']:.2f}", att[key]["seconds"])
            for name, key in (("Average attention", "average_attention"), ("AT2", "at2"), ("ContextCite", "contextcite"))]
    for name, run in (("Evidence head, softmax encoder", EV_LIST), ("Evidence head, sigmoid-norm encoder", EV_SIG)):
        f = data._json(data.RUNS / run / "metrics.json")
        if f:
            e = f["ALL"]
            rows.append((name, e["sentence_ap"], e["sentence_top1"], "--", e["seconds"]))
    body = []
    for i, (name, ap, top1, lds, sec) in enumerate(rows):
        if i == 3:
            body.append("\\midrule")
        ms = f"{1000 * sec:,.0f}".replace(",", "{,}")
        body.append(f"{name} & {ap:.2f} & {100 * top1:.0f} & {lds} & {ms} \\\\")
    (OUT / "table_citation.tex").write_text(
        "% Generated by paper/figures/make_figures.py; do not edit.\n"
        "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
        "Method & Sentence AP & Top-1 (\\%) & LDS & ms per row \\\\\n\\midrule\n"
        + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")


def table_ablation():
    """Loss and answer-word variants of the encoder: dev ALL, external, three datasets (one seed, dev rows)."""
    rows = []
    for name, run in ABLATION:
        f = data._json(data.RUNS / run / "eval_final.json")
        cells = [pct(data.dev_all(run)), pct(data.external(run))] + [pct(f[d]["accuracy"]) for d in ("musique", "contractnli", "nimble")]
        rows.append(f"{name} & " + " & ".join(cells) + " \\\\")
    (OUT / "table_ablation.tex").write_text(
        "% Generated by paper/figures/make_figures.py; do not edit.\n"
        "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\n"
        "Variant & Dev ALL & External & MuSiQue & ContractNLI & Nimble \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def fig_lr():
    """Dev ALL and external macro against the learning rate, one line per model/loss (one seed per point)."""
    fig, axes = plt.subplots(1, 2, figsize=(style.FULL, 2.1), sharex=True)
    look = {"ub_sig": (style.ENCODER, "-", "o", "UltraBERT sigmoid_norm"),
            "ub_list": (style.ENCODER, (0, (4, 2)), "s", "UltraBERT softmax"),
            "qw_full": (style.DECODER, "-", "o", "Qwen3-0.6B full FT")}
    for ax, (fn, label) in zip(axes, ((data.dev_all, "Held-out ALL, dev (%)"), (data.external, "External macro (%)"))):
        for k, runs in data.SWEEPS.items():
            c, ls, mk, name = look[k]
            pts = [(lr, fn(run)) for lr, run in runs if fn(run) is not None]
            ax.plot([p[0] for p in pts], [100 * p[1] for p in pts], color=c, ls=ls, marker=mk, ms=4.5, label=name)
        ax.set_xscale("log")
        ax.set_xticks([5e-6, 1e-5, 2e-5, 5e-5], ["5e-6", "1e-5", "2e-5", "5e-5"])
        ax.minorticks_off()
        ax.set_xlabel("Learning rate")
        ax.set_ylabel(label)
    axes[1].legend(loc="lower left", handlelength=2.2)
    fig.tight_layout()
    fig.savefig(OUT / "fig_lr.pdf")
    plt.close(fig)


def numbers(h, diffs):
    """numbers.tex: e.g. \\TestUbSig{72.1}, \\TestUbSigCI{[71.0, 73.0]}, \\DiffUbSigQwFull{+4.4}."""
    lines = ["% Generated by paper/figures/make_figures.py; do not edit."]
    for k, r in h.items():
        n = MACRO[k]
        if r["test"]:
            pt, lo, hi = r["test"]
            lines += [f"\\newcommand{{\\Test{n}}}{{{pct(pt)}}}", f"\\newcommand{{\\Test{n}CI}}{{[{pct(lo)}, {pct(hi)}]}}"]
        if r["dev"][0] is not None:
            lines.append(f"\\newcommand{{\\Dev{n}}}{{{pct(r['dev'][0])}}}")
        if r["ext"][0] is not None:
            lines.append(f"\\newcommand{{\\Ext{n}}}{{{pct(r['ext'][0])}}}")
    for (a, b), (pt, lo, hi) in diffs.items():
        n = f"Diff{MACRO[a]}{MACRO[b]}"
        lines += [f"\\newcommand{{\\{n}}}{{{100 * pt:+.1f}}}",
                  f"\\newcommand{{\\{n}CI}}{{[{100 * lo:+.1f}, {100 * hi:+.1f}]}}"]
    gap = h["ub_sig"]["test"][0] - h["qw_lora"]["test"][0]
    lines.append(f"\\newcommand{{\\DiffUbSigQwLoraText}}{{{100 * gap:.1f}}}")
    for tag, name in ((EV_LIST, "List"), ("evidence_ultrabert_380m_gold", "Gold"), (EV_SIG, "Sig")):
        if not (data.RUNS / tag / "metrics.json").exists():
            continue
        ev = json.loads((data.RUNS / tag / "metrics.json").read_text())["ALL"]
        lines += [f"\\newcommand{{\\EvSentAP{name}}}{{{ev['sentence_ap']:.2f}}}",
                  f"\\newcommand{{\\EvTokAP{name}}}{{{ev['token_ap']:.2f}}}",
                  f"\\newcommand{{\\EvTopOne{name}}}{{{100 * ev['sentence_top1']:.0f}}}",
                  f"\\newcommand{{\\EvPTen{name}}}{{{ev['token_p@10']:.2f}}}",
                  f"\\newcommand{{\\EvChance{name}}}{{{ev['gold_share']:.2f}}}",
                  f"\\newcommand{{\\EvMs{name}}}{{{1000 * ev['seconds']:.0f}}}"]
        th = data._json(data.RUNS / tag / "threshold.json")
        if th:
            w = th["report"]["ALL"]
            lines += [f"\\newcommand{{\\EvThr{name}}}{{{th['threshold']:.2f}}}",
                      f"\\newcommand{{\\EvWordP{name}}}{{{w['precision']:.2f}}}",
                      f"\\newcommand{{\\EvWordR{name}}}{{{w['recall']:.2f}}}"]
    att = json.loads((data.RUNS / "at2_ultrabert_380m" / "attribution_eval.json").read_text())["summary"]["ALL"]
    for key, name in (("at2", "AtTwo"), ("contextcite", "ContextCite")):
        lines += [f"\\newcommand{{\\{name}SentAP}}{{{att[key]['ap']:.2f}}}",
                  f"\\newcommand{{\\{name}TopOne}}{{{100 * att[key]['top1']:.0f}}}",
                  f"\\newcommand{{\\{name}Lds}}{{{att[key]['lds']:.2f}}}",
                  f"\\newcommand{{\\{name}Ms}}{{{1000 * att[key]['seconds']:,.0f}}}".replace(",", "{,}")]
    rows = next(r["rows"] for r in h.values() if r["rows"])
    lat = json.loads((data.RUNS / "latency.json").read_text())["models"]
    ms = {k: v["latency"]["mean_ms"] for k, v in lat.items()}
    lines += [f"\\newcommand{{\\MsUb}}{{{ms['runs/ultrabert_380m_lr1.5e-5 (fp32 weights)']:.0f}}}",
              f"\\newcommand{{\\MsQwFull}}{{{ms['Athekunal/llm-jev-qwen3-0.6b']:.0f}}}",
              f"\\newcommand{{\\MsQwFourLora}}{{{ms['Athekunal/llm-jev-qwen3-4b']:.0f}}}"]
    var = lat["runs/ultrabert_380m_lr1.5e-5 (fp32 weights, FA2 varlen)"]["throughput"]["rows_per_s"]
    lines += [f"\\newcommand{{\\RpsUb}}{{{var:.1f}}}",
              f"\\newcommand{{\\RpsQwFull}}{{{lat['Athekunal/llm-jev-qwen3-0.6b']['throughput']['rows_per_s']:.1f}}}"]
    man = json.loads((data.ROOT / "data/splits/reason_long_nimble/manifest.json").read_text())
    n_test = len(next(r["rows"] for r in h.values() if r["rows"]))
    lines += [f"\\newcommand{{\\NTrain}}{{{man['totals']['train']:,}}}".replace(",", "{,}"),
              f"\\newcommand{{\\NHeldOut}}{{{man['totals']['eval']:,}}}".replace(",", "{,}"),
              f"\\newcommand{{\\NDev}}{{{man['totals']['eval'] - n_test:,}}}".replace(",", "{,}"),
              f"\\newcommand{{\\MaxTokens}}{{{man['max_tokens']:,}}}".replace(",", "{,}"),
              f"\\newcommand{{\\NPerDataset}}{{{man['mixture']['piqa']:,}}}".replace(",", "{,}")]
    lines.append(f"\\newcommand{{\\NTest}}{{{len(rows):,}}}".replace(",", "{,}"))
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n")


def main():
    OUT.mkdir(exist_ok=True)
    style.apply()
    h = data.headline()
    diffs = data.paired(h)
    fig_headline(h)
    table_headline(h)
    table_perdataset(h)
    table_ablation()
    table_citation()
    make_examples.main()
    numbers(h, diffs)
    print(f"wrote {sorted(p.name for p in OUT.iterdir())}")


if __name__ == "__main__":
    main()
