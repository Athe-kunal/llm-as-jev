    for k, r in h.items():
        n = MACRO[k]
        if r["test"]:
            pt, lo, hi = r["test"]
            lines += [f"\\newcommand{{\\Test{n}}}{{{pct(pt)}}}", f"\\newcommand{{\\Test{n}CI}}{{[{pct(lo)}, {pct(hi)}]}}"]
        if r["dev"][0] is not None:
            lines.append(f"\\newcommand{{\\Dev{n}}}{{{pct(r['dev'][0])}}}")
        if r["ext"][0] is not None:
            lines.append(f"\\newcommand{{\\Ext{n}}}{{{pct(r['ext'][0])}}}")
