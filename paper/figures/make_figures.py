def max_grad_norm(run):
    """Largest pre-clipping gradient norm logged during training."""
    from tensorboard.backend.event_processing.event_accumulator import EventAccumulator
    acc = EventAccumulator(str(next((data.RUNS / run / "tb").iterdir())))
    acc.Reload()
    return max(x.value for x in acc.Scalars("train/grad_norm"))


