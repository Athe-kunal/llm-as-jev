"""Renders figures/examples.json (see export_examples.py) as generated/examples.tex.

Per example: the decision (option probabilities, gold and predicted marked) and the document with the tokens
that the evidence head scores at or above the tuned threshold highlighted (darker for a higher probability
for the predicted option). Tokens inside the gold evidence are underlined.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / "generated"
BLUE = (0x2A, 0x78, 0xD6)          # = style.ENCODER
MAX_ALPHA = 0.75                   # shading at p = 1
NAMES = {"contractnli": "ContractNLI", "nimble": "Nimble", "proofwriter": "ProofWriter", "musique": "MuSiQue"}
SPECIAL = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}",
           "\uf0b7": r"\textbullet{}", "—": "---", "–": "--", "“": "``", "”": "''", "‘": "`", "’": "'"}


def esc(text):
    return "".join(SPECIAL.get(c, c) for c in text)


def shade(p, threshold):
    """Shading from 35% of MAX_ALPHA at the threshold to MAX_ALPHA at p = 1."""
    a = MAX_ALPHA * (0.35 + 0.65 * (p - threshold) / (1 - threshold))
    return "".join(f"{round(255 - a * (255 - c)):02X}" for c in BLUE)


def render_part(text, tokens, gold, threshold):
    """The part's text with its tokens shaded; characters between tokens are plain."""
    toks = sorted((t for t in tokens), key=lambda t: t["start"])
    out, cursor = [], 0

    def plain(s):
        s = s.replace("\n\n", "\x00").replace("\n", " ")
        return esc(s).replace("\x00", "\n\n")

    for t in toks:
        if t["start"] < cursor:
            continue
        out.append(plain(text[cursor:t["start"]]))
        raw = text[t["start"]:t["end"]]
        body = raw.lstrip()
        out.append(plain(raw[: len(raw) - len(body)]))          # the token's leading space stays breakable
        s, e = t["start"] + len(raw) - len(body), t["end"]
        body = body.replace("\n", " ")
        if body:
            piece = esc(body)
            if any(g["start"] < e and g["end"] > s for g in gold):
                piece = rf"\underline{{{piece}}}"
            if t["p"] >= threshold:
                piece = rf"{{\fboxsep=0pt\colorbox[HTML]{{{shade(t['p'], threshold)}}}{{{piece}}}}}"
            out.append(piece)
        cursor = t["end"]
    out.append(plain(text[cursor:]))
    return "".join(out)


def render(key, ex):
    row, ev = ex["row"], ex["evidence"]
    ok = row["answer"] == row["gold"]
    lines = [rf"\paragraph{{{NAMES.get(key, key)}.}} {row['tokens']:,} tokens.".replace(",", "{,}"),
             rf"The model chooses option {row['answer'] + 1}, which is \textbf{{{'correct' if ok else 'incorrect'}}}."
             rf" Question: {esc(row['question']).replace(chr(10), ' ')}", "",
             r"\begin{tabular}{@{}rrp{0.7\linewidth}l@{}}", r"\toprule",
             r"$k$ & Probability & Option & \\", r"\midrule"]
    for k, (opt, q) in enumerate(zip(row["options"], row["q"])):
        tag = ", ".join(t for t, cond in (("gold", k == row["gold"]), ("chosen", k == row["answer"])) if cond)
        lines.append(rf"{k + 1} & {100 * q:.0f}\% & {esc(opt)} & {tag} \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    by_part = {}
    for t in ev["tokens"]:
        by_part.setdefault(t["part"], []).append(t)
    lines.append(r"\begingroup\scriptsize\setlength{\parindent}{0pt}\setlength{\parskip}{0.3em}\raggedright")
    for i, (name, text) in enumerate(zip(row["parts"], row["partTexts"])):
        gold = [s for s in row["spans"] if s["part"] == i]
        lines.append(rf"\textsf{{\textbf{{{esc(name)}}}}}\quad "
                     + render_part(text, by_part.get(i, []), gold, ev["threshold"]) + "\n")
    lines.append(r"\endgroup")
    return "\n".join(lines)


def main():
    d = json.loads((HERE / "examples.json").read_text())
    body = "\n\n".join(render(k, v) for k, v in d["examples"].items())
    (OUT / "examples.tex").write_text("% Generated by paper/figures/make_examples.py; do not edit.\n" + body + "\n")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    main()
